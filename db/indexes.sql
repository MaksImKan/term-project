-- =============================================================================
-- Marketplace API — мінімальний набір індексів, що лікує q1..q4 (ДЗ-12)
--
-- Мінімальний означає буквально: чотири індекси на чотири запити, жодного
-- «про запас». Кожен зайвий індекс — це диск, повільніший INSERT/UPDATE і
-- робота для autovacuum. Перевірка, що жоден не мертвий:
--
--   SELECT indexrelname, idx_scan FROM pg_stat_user_indexes
--   WHERE schemaname = 'public'
--     AND indexrelid NOT IN (SELECT conindid FROM pg_constraint WHERE conindid <> 0)
--   ORDER BY idx_scan;
--
-- Індексів під FOREIGN KEY тут свідомо немає: жоден із чотирьох запитів їх не
-- використовує, тож вони лишились би мертвими. Вони знадобляться тоді, коли
-- зʼявиться запит або каскадне видалення, яким вони потрібні.
-- =============================================================================

-- q1 — «замовлення покупця за період».
-- Складений індекс у порядку «спочатку рівність, потім діапазон»: за buyer_id
-- індекс позиціонується, а далі йде вже впорядкований діапазон created_at, тож
-- ORDER BY created_at DESC LIMIT 50 отримує рядки готовими, без вузла Sort.
CREATE INDEX idx_orders_buyer_created_at
  ON orders (buyer_id, created_at DESC);

-- q2 — «черга необроблених замовлень».
-- PARTIAL: у WHERE індексу той самий предикат, що й у запиті. Статус pending —
-- це 5% таблиці, тож індекс у ~20 разів менший за повний по (status,
-- created_at), а впорядкованість по created_at DESC віддає LIMIT 100 одразу.
-- Саме такий індекс повний індекс по status ігнорував би: 5% від 200 000 —
-- завелика частка, щоб лізти в індекс по одному лише статусу.
CREATE INDEX idx_orders_pending_created_at
  ON orders (created_at DESC)
  WHERE status = 'pending';

-- q3 — «знайти користувача за email без урахування регістру».
-- EXPRESSION: у WHERE стоїть функція lower(email), а не колонка, тож індекс по
-- колонці email планер використати не може — потрібен індекс по тому самому
-- виразу. UNIQUE заразом забороняє двох користувачів, що різняться лише
-- регістром email.
CREATE UNIQUE INDEX idx_users_lower_email
  ON users (lower(email));

-- q4 — повнотекстовий пошук по каталогу.
-- GIN по збереженій генерованій колонці search_vector: GIN — інвертований
-- індекс, він зберігає «лексема -> список рядків», і це єдиний тип індексу, що
-- вміє оператор @@. B-tree тут неможливий у принципі: він індексує значення
-- цілком, а не слова в ньому.
CREATE INDEX idx_products_search_vector
  ON products USING GIN (search_vector);
